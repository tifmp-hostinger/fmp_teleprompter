export const LANGS = { 'pt-BR': 'Português (Brasil)', en: 'English', es: 'Español' };
const STORAGE_KEY = 'fmp.tp.lang';
let current = detectLang();

function detectLang() {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved && STRINGS[saved]) return saved;
  } catch { /* sem storage */ }
  const nav = (navigator.language || 'pt-BR');
  if (nav.startsWith('pt')) return 'pt-BR';
  if (nav.startsWith('es')) return 'es';
  return 'en';
}

export function getLang() { return current; }

export function setLang(code) {
  if (!STRINGS[code]) return;
  current = code;
  try { localStorage.setItem(STORAGE_KEY, code); } catch { /* ignore */ }
  document.documentElement.lang = code;
  applyTranslations(document);
}

export function t(key, vars = {}) {
  const str = STRINGS[current][key] ?? STRINGS.en[key] ?? key;
  return str.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? `{${k}}`));
}

/** Aplica traduções em elementos com data-i18n / data-i18n-placeholder / data-i18n-title. */
export function applyTranslations(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll('[data-i18n-placeholder]').forEach((el) => { el.placeholder = t(el.dataset.i18nPlaceholder); });
  root.querySelectorAll('[data-i18n-title]').forEach((el) => {
    el.title = t(el.dataset.i18nTitle);
    el.setAttribute('aria-label', t(el.dataset.i18nTitle));
  });
  document.title = t('appName');
}

